'use strict';
/*
 * node tools/build.js [--check]
 * Scans core/ui-*.js|css, content/*.js and games/*.js (sorted; names starting with "_" are skipped) and writes
 * generated/manifest.js:  window.__POINTLESS_FILES = { content:[...], games:[...], ui:[...], css:[...] }
 * The file is only rewritten when its content changes, and always by atomic rename (retried with backoff), so concurrent runs are
 * safe and a browser can never load a half-written manifest.
 *
 * IMPORTANT: a player double-clicks index.html and there is no build step, so run this (or selftest/shot, which run it) after adding,
 * renaming or deleting a file, and ALWAYS before shipping. `node tools/build.js --check` exits 1 when generated/manifest.js is stale.
 *
 * Names that cannot be loaded safely are skipped with a warning: games/<id>.js must be kebab-case (a-z, 0-9, dashes); content files
 * may use letters, digits, dot, dash and underscore; directories and anything else are ignored.
 * Also exported: require('./build.js').build() -> manifest object.
 */
const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const GAME_RE = /^[a-z0-9]+(?:-[a-z0-9]+)*\.js$/;
const CONTENT_RE = /^[A-Za-z0-9][A-Za-z0-9._-]*\.js$/;
const UI_JS_RE = /^ui-[A-Za-z0-9._-]+\.js$/;
const UI_CSS_RE = /^ui-[A-Za-z0-9._-]+\.css$/;

function sleepSync(ms) { try { Atomics.wait(new Int32Array(new SharedArrayBuffer(4)), 0, 0, ms); } catch (e) { /* ignore */ } }

function list(dir, looksLike, valid, skipped) {
  const abs = path.join(ROOT, dir);
  let names = [];
  try { names = fs.readdirSync(abs); } catch (e) { return []; }
  return names
    .filter((n) => {
      if (n.startsWith('_') || !looksLike(n)) return false;
      let isFile = false;
      try { isFile = fs.statSync(path.join(abs, n)).isFile(); } catch (e) { return false; }     // directories (even one called "x.js") are ignored
      if (!isFile) return false;
      if (!valid(n)) { skipped.push(dir + '/' + n); return false; }
      return true;
    })
    .sort((a, b) => (a < b ? -1 : a > b ? 1 : 0))
    .map((n) => dir + '/' + n);
}

function scan() {
  const skipped = [];
  return {
    content: list('content', (n) => /\.js$/.test(n), (n) => CONTENT_RE.test(n), skipped),
    games: list('games', (n) => /\.js$/.test(n), (n) => GAME_RE.test(n), skipped),
    ui: list('core', (n) => /^ui-.*\.js$/.test(n), (n) => UI_JS_RE.test(n), skipped),
    css: list('core', (n) => /^ui-.*\.css$/.test(n), (n) => UI_CSS_RE.test(n), skipped),
    skipped: skipped
  };
}

function render(m) {
  const j = (a) => '[' + a.map((s) => JSON.stringify(s)).join(',\n    ') + ']';
  return '/* GENERATED by tools/build.js - do not edit. */\n' +
    'window.__POINTLESS_FILES = {\n' +
    '  ui: ' + j(m.ui) + ',\n' +
    '  css: ' + j(m.css) + ',\n' +
    '  content: ' + j(m.content) + ',\n' +
    '  games: ' + j(m.games) + '\n' +
    '};\n';
}

function build(opts) {
  opts = opts || {};
  const m = scan();
  const text = render(m);
  const dir = path.join(ROOT, 'generated');
  const file = path.join(dir, 'manifest.js');
  fs.mkdirSync(dir, { recursive: true });
  const read = () => { try { return fs.readFileSync(file, 'utf8'); } catch (e) { return null; } };
  let wrote = false;
  if (read() !== text) {
    const tmp = file + '.' + process.pid + '.' + Math.random().toString(36).slice(2) + '.tmp';
    fs.writeFileSync(tmp, text, 'utf8');
    /* Windows can refuse a rename for a moment while another process (or a browser) has the target open: retry with backoff.
     * Never fall back to writing the file in place: that is what lets a reader see an empty manifest. */
    for (let i = 0; i < 14 && !wrote; i++) {
      try { fs.renameSync(tmp, file); wrote = true; }
      catch (e) {
        if (read() === text) break;                  // somebody else already published exactly this content
        sleepSync(15 + i * 30);
      }
    }
    try { fs.unlinkSync(tmp); } catch (e) { /* already renamed or gone */ }
    if (!wrote && read() !== text && !opts.quiet) console.error('warning: could not replace generated/manifest.js (still in use?); the old manifest is intact. Run node tools/build.js again.');
  }
  m.wrote = wrote;
  if (!opts.quiet) {
    console.log('manifest: ' + m.games.length + ' game(s), ' + m.content.length + ' content file(s), ' + m.ui.length + ' ui script(s), ' + m.css.length + ' ui css' +
      (wrote ? ' (written)' : ' (unchanged)'));
    m.skipped.forEach((s) => console.warn('warning: skipped ' + s + ' (games/<id>.js must be kebab-case; file names may only use letters, digits, dot, dash, underscore)'));
  }
  return m;
}

/** exit-code friendly check: is generated/manifest.js what a build would write right now? */
function check() {
  const m = scan();
  const want = render(m);
  let have = null;
  try { have = fs.readFileSync(path.join(ROOT, 'generated', 'manifest.js'), 'utf8'); } catch (e) { /* missing */ }
  return { ok: have === want, missing: have === null, manifest: m };
}

module.exports = { build, scan, render, check, ROOT };

if (require.main === module) {
  if (process.argv.includes('--check')) {
    const r = check();
    if (r.ok) { console.log('manifest is up to date (' + r.manifest.games.length + ' game(s), ' + r.manifest.content.length + ' content file(s))'); process.exit(0); }
    console.error('generated/manifest.js is ' + (r.missing ? 'missing' : 'STALE') + ': it does not match the files on disk. Run: node tools/build.js');
    process.exit(1);
  }
  build();
}
